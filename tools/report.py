import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "eval"
LOG = ROOT / "backend/logs/calls.jsonl"
FIELDS = ["make", "model", "serial", "mfg_date", "damage_type", "size_cm", "location", "issue", "material", "severity"]


def pct(a, n):
    return f"{100 * a / n:.0f}% ({a}/{n})" if n else "- (0)"


def mean(xs):
    return f"{sum(xs) / len(xs):.2f}" if xs else "-"


def right(r):
    return r["outcome"] in ("correct", "null_ok")


def table(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def acc_rows(sel, key):
    out = []
    for k in sorted({key(r) for r in sel}, key=str):
        g = [r for r in sel if key(r) == k]
        c = [float(r["confidence"]) for r in g if r["outcome"] == "correct"]
        w = [float(r["confidence"]) for r in g if r["outcome"] == "wrong"]
        out.append([k, len(g), pct(sum(map(right, g)), len(g)), sum(r["outcome"] == "wrong" for r in g), sum(r["outcome"] == "missed" for r in g), mean(c), mean(w)])
    return out


HEAD = ["", "n", "right (incl. correct null)", "wrong", "missed", "conf correct", "conf wrong"]


def main():
    rows = list(csv.DictReader(open(OUT / "results.csv")))
    comb = [r for r in rows if r["source"] == "combined"]
    md = ["# Evaluation report", "",
          "Generated by `tools/eval.py` + `tools/report.py` from `eval/results.csv` (re-runs from `eval/cache/`, no API calls).",
          "Right = correct value, or null where the label says the field is absent/unreadable. Every percentage has its count.", ""]

    frames = {(r["file"], r["type"], r["variant"], r["split"]) for r in comb}
    md += ["## T1 Test set composition (frames)", "",
           table(["type", "variant", "tune", "eval"], [[t, v, sum(1 for f in frames if f[1] == t and f[2] == v and f[3] == "tune"),
                                                     sum(1 for f in frames if f[1] == t and f[2] == v and f[3] == "eval")]
                                                    for t, v in sorted({(f[1], f[2]) for f in frames})]), ""]

    ev = [r for r in comb if r["split"] == "eval"]
    md += ["## T2 Accuracy per field (eval split, original photos and notes)", "",
           table(HEAD, acc_rows([r for r in ev if r["variant"] in ("orig", "injected", "asr_quiet", "asr_noisy", "authored")], lambda r: r["field"])), ""]
    ml = [r for r in rows if r["source"] == "mlkit" and r["split"] == "eval" and r["variant"] == "orig"]
    if ml:
        md += ["Baseline, ML Kit + rules only (same eval nameplates):", "", table(HEAD, acc_rows(ml, lambda r: r["field"])), ""]

    md += ["## T3 Accuracy by condition (eval split, all fields of photos)", "",
           table(HEAD, acc_rows([r for r in ev if r["type"] != "note"], lambda r: f"{r['type']} / {r['variant']}")), "",
           "Lighting (low = synthetic dark variants + photos labelled low light):", "",
           table(HEAD, acc_rows([r for r in ev if r["type"] != "note"], lambda r: f"{r['type']} / light {r['lighting']}")), ""]
    notes = [r for r in comb if r["type"] == "note"]
    if notes:
        md += ["Notes by source (real ASR vs typed):", "", table(HEAD, acc_rows(notes, lambda r: r["variant"])), ""]

    buckets = [(0, 0.5), (0.5, 0.8), (0.8, 1.01)]
    preds = [r for r in ev if r["predicted"] not in ("", None)]
    md += ["## T4 Calibration (eval split, every non-null prediction)", "",
           table(["confidence", "n", "correct"], [[f"{a:.1f}-{min(b, 1):.1f}", sum(a <= float(r["confidence"]) < b for r in preds),
                                                   pct(sum(a <= float(r["confidence"]) < b and r["outcome"] == "correct" for r in preds),
                                                       sum(a <= float(r["confidence"]) < b for r in preds))] for a, b in buckets]), "",
           f"Mean confidence: correct {mean([float(r['confidence']) for r in preds if r['outcome'] == 'correct'])}, "
           f"wrong {mean([float(r['confidence']) for r in preds if r['outcome'] == 'wrong'])}.", ""]

    photos = [r for r in ev if r["type"] != "note"]
    md += ["## T5 Quality gate effect (eval split)", "",
           table(HEAD, acc_rows(photos, lambda r: f"{r['type']} / gate {'passed' if r['gate_passed'] == '1' else 'rejected'}")), ""]

    causes = {}
    fn = OUT / "failure_notes.csv"
    if fn.exists():
        causes = {(r["file"], r["field"]): r for r in csv.DictReader(open(fn))}
    worst = sorted([r for r in ev if r["outcome"] == "wrong"], key=lambda r: -float(r["confidence"]))[:5]
    md += ["## T6 Five worst failures (highest-confidence wrong answers, eval split)", "",
           table(["#", "image", "field", "truth", "predicted", "confidence", "cause", "fix idea"],
                 [[i + 1, f"`{r['file']}`", r["field"], r["truth"], r["predicted"], r["confidence"],
                   causes.get((r["file"], r["field"]), {}).get("cause", "TBD"), causes.get((r["file"], r["field"]), {}).get("fix", "TBD")]
                  for i, r in enumerate(worst)]), ""]

    calls = [json.loads(l) for l in LOG.read_text().splitlines()] if LOG.exists() else []
    by = Counter((c["model"], c["status"]) for c in calls)
    ok = [c for c in calls if c["status"] == 200]
    md += ["## Cost", "", table(["model", "status", "calls"], [[m, s, n] for (m, s), n in sorted(by.items(), key=str)]), "",
           f"Successful calls {len(ok)}, input tokens {sum(c.get('in_tokens') or 0 for c in ok)}, output tokens "
           f"{sum(c.get('out_tokens') or 0 for c in ok)}, thinking tokens {sum(c.get('thought_tokens') or 0 for c in ok)}. "
           "All on the AI Studio free tier: $0 billed (free-tier requests may be used by Google to improve its models).", ""]
    (OUT / "REPORT.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
